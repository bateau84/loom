import { test } from 'node:test'
import assert from 'node:assert/strict'
import { DatabaseSync } from 'node:sqlite'
import { readFileSync } from 'node:fs'
import { Store } from '../.test-build/store.js'
import { workReference } from '../.test-build/collaboration.js'

const actor = { session_id: 'current', agent: 'author' }
const frozen = JSON.parse(readFileSync(new URL('./fixtures/baseline-c9ffcfa/snapshot.json', import.meta.url), 'utf8'))
const ids = JSON.parse(readFileSync(new URL('./fixtures/baseline-c9ffcfa/ids.json', import.meta.url), 'utf8'))
function fixture(t) {
  const db = new DatabaseSync(':memory:'); t.after(() => db.close())
  db.exec('PRAGMA foreign_keys=OFF')
  // Portable frozen input, generated by the baseline implementation, not a
  // reconstruction of candidate outputs. No Git objects or old runtime required.
  for (const row of frozen.schema.filter(r => r.type === 'table' && r.name !== 'sqlite_sequence')) db.exec(row.sql)
  for (const [table, rows] of Object.entries(frozen.tables)) {
    db.exec(`DELETE FROM "${table}"`)
    for (const row of rows) db.prepare(`INSERT INTO "${table}" (${Object.keys(row).map(k => `"${k}"`).join(',')}) VALUES (${Object.keys(row).map(() => '?').join(',')})`).run(...Object.values(row))
  }
  for (const row of frozen.schema.filter(r => r.type !== 'table' && r.sql)) db.exec(row.sql)
  db.exec(`PRAGMA user_version=${frozen.user_version}`)
  const all = () => ({ schema: db.prepare('SELECT type,name,tbl_name,sql FROM sqlite_schema ORDER BY type,name').all().map(r => ({ ...r })),
    tables: Object.fromEntries(Object.keys(frozen.tables).map(table => [table, db.prepare(`SELECT * FROM "${table}" ORDER BY rowid`).all().map(r => ({ ...r }))])) })
  return { db, all, store: new Store(db) }
}
test('populated old tables, raw ledger bytes, IDs, links and completion qualifications survive candidate restart and reads', t => {
  const f = fixture(t), before = f.all()
  for (let restart = 0; restart < 2; restart++) {
    const store = new Store(f.db)
    assert.equal(store.delivery, undefined)
    assert.equal(store.collaboration.assign, undefined)
    assert.equal(store.collaboration.coordinationRecords, undefined)
    for (const row of frozen.tables.ledger) {
      const record = JSON.parse(row.data)
      const found = store.records({ ...(record.action_id ? { action_id: record.action_id } : { session_id: record.session_id }), record_id: row.id }).items[0]
      assert.deepEqual(found, { sequence: row.seq, ...record })
    }
    const answers = frozen.tables.ledger.filter(row => row.kind === 'answer').map(row => ({ sequence: row.seq, ...JSON.parse(row.data) }))
      .filter(row => row.data.question_id === ids.question.id)
    assert.deepEqual(store.collaboration.thread(ids.question.id).answers, answers)
    assert.equal(store.collaboration.progress(ids.action.id, 'work').items[0].state, 'needs-reconfirmation')
    assert.equal(store.collaboration.progress(ids.action.id, 'reopened').items[0].state, 'open')
    assert.deepEqual(f.all(), before)
  }
})
