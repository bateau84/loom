test('plain completion keeps original work_ref and goal through replanning and reopen, without assignment machinery', t => {
  const f = fixture(t), c = f.store.collaboration, action = f.store.create('Original', 'Original goal', actor)
  const plan = f.store.savePlan(action.id, 0, [{ id: 'work', kind: 'task', title: 'Original work' }, { id: 'other', kind: 'task', title: 'Sibling' }])
  const ref = workReference(action, plan, 'work')
  f.store.savePlan(action.id, 1, [plan.nodes[0], { ...plan.nodes[1], title: 'Changed sibling' }])
  const complete = c.complete(actor, { work_ref: ref, statement: 'Qualified, not acceptance' })
  assert.deepEqual(complete.data.work_ref, ref); assert.deepEqual(complete.data.work_goal, { title: 'Original', goal: 'Original goal' })
  assert.equal(c.progress(action.id, 'work').items[0].state, 'reported-complete')
  assert.equal(c.progress(action.id, 'other').items[0].state, 'open')
  f.store.update(action.id, 1, { goal: 'Different goal' })
  assert.equal(c.progress(action.id, 'work').items[0].state, 'needs-reconfirmation')
  c.reopen(actor, { action_id: action.id, node_id: 'work' }, 'Explicit reason')
  assert.equal(c.progress(action.id, 'work').items[0].state, 'open')
  assert.equal(f.store.action(action.id).state, 'active')
})
